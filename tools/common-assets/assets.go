package main

import (
	"fmt"
	"strings"
)

// requiredActions are the fightfx numbers the sources name even before the
// census: Ikemen GO's default spark numbers (char.go:341 sparkno 2, char.go:342
// guard.sparkno 40) and the ground-bounce dust the common states play
// (common1.cns:1523, anim = F(60 + 0..2)).
var requiredActions = []int{2, 40, 60, 61, 62}

// requiredSounds are the common sounds the sources name: the MUGEN docs'
// hitsound 5,0 to 5,4 and guardsound 6,0, and the ground-bounce sounds of the
// common states (common1.cns:1534, value = F7, 0..2).
var requiredSounds = [][2]int{{5, 0}, {5, 1}, {5, 2}, {5, 3}, {5, 4}, {6, 0}, {7, 0}, {7, 1}, {7, 2}}

// effect is one family of sprites: its frames share a sprite group and are
// drawn by the same function at a given size.
type effect struct {
	name   string
	size   int
	frames int
	ticks  int // game ticks each frame is shown
	color  [3]uint8
	draw   func(x, y, t float64) float64
}

const frameCount = 5

// effects is indexed by sprite group.
var effects = []effect{
	{"hit spark, light", 48, frameCount, 2, [3]uint8{255, 190, 60}, burst(6, 0)},
	{"hit spark, medium", 64, frameCount, 2, [3]uint8{255, 170, 50}, burst(8, 0)},
	{"hit spark, heavy", 80, frameCount, 3, [3]uint8{255, 140, 40}, burst(10, 0.5)},
	{"hit spark, big", 96, frameCount, 3, [3]uint8{255, 110, 40}, burst(12, 1)},
	{"guard spark, light", 48, frameCount, 2, [3]uint8{70, 150, 255}, shield(0.7)},
	{"guard spark, medium", 64, frameCount, 2, [3]uint8{60, 140, 255}, shield(0.85)},
	{"guard spark, heavy", 80, frameCount, 3, [3]uint8{80, 170, 255}, shield(1)},
	{"dust, small", 48, frameCount, 3, [3]uint8{200, 190, 170}, dust(0.7)},
	{"dust, medium", 64, frameCount, 3, [3]uint8{200, 190, 170}, dust(0.85)},
	{"dust, large", 80, frameCount, 3, [3]uint8{200, 190, 170}, dust(1)},
	{"shock ring", 96, frameCount, 3, [3]uint8{150, 230, 255}, ring},
	{"flash", 112, frameCount, 3, [3]uint8{255, 220, 120}, flash},
}

// Sprite groups of the effects the sources give a meaning to.
const (
	groupHitLight = iota
	groupHitMedium
	groupHitHeavy
	groupHitBig
	groupGuardLight
	groupGuardMedium
	groupGuardHeavy
	groupDustSmall
	groupDustMedium
	groupDustLarge
)

// namedActions gives the action numbers the sources describe their effect:
// the engine's default spark (2) and guard spark (40), the hit sparks 0 to 3
// and guard sparks 40 to 42 real characters use most (CENSUS.md), and the
// ground-bounce dust 60 to 62 (common1.cns:1523).
var namedActions = map[int]int{
	0: groupHitLight, 1: groupHitMedium, 2: groupHitHeavy, 3: groupHitBig,
	40: groupGuardLight, 41: groupGuardMedium, 42: groupGuardHeavy,
	60: groupDustSmall, 61: groupDustMedium, 62: groupDustLarge,
}

// groupOf returns the sprite group an action plays. A number the sources do
// not describe plays an effect picked from its value, so it still resolves.
func groupOf(action int) int {
	group, ok := namedActions[action]
	if ok {
		return group
	}
	return action % len(effects)
}

// airText writes fightfx.air: one action per number, playing the frames of
// its effect once.
func airText(actions []int) string {
	var b strings.Builder
	b.WriteString("; OpenKakutou common effects, generated by tools/common-assets. CC0.\n")
	for _, action := range actions {
		group := groupOf(action)
		e := effects[group]
		fmt.Fprintf(&b, "\n[Begin Action %d]\n", action)
		for frame := 0; frame < e.frames; frame++ {
			fmt.Fprintf(&b, "%d,%d, 0,0, %d, , A\n", group, frame, e.ticks)
		}
	}
	return b.String()
}
